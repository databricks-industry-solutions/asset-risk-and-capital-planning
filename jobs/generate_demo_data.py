# ARMOR demo data job: write a fictional utility (armor.demo) into the asset data model, so the accelerator runs as-is.
#
#   --input_schema   <catalog>.<schema> to create and fill with the demo asset data model (overwritten)
#   --output_schema  <catalog>.<schema> the model job writes (created here so the app can be granted on it up front)
#   --app_name       the ARMOR app; its service principal is granted read access on both schemas
#   --seed / --n_feeders / --as_of   size and shape of the demo utility (as_of default: Jan 1 of this year)
#   --src_dir        workspace folder holding src/ (serverless spark_python_task has no __file__)
#
# For your own data you don't run this: point input_schema at views over your tables instead (README, "Make it yours").
import argparse
import sys
from datetime import date

ap = argparse.ArgumentParser()
ap.add_argument("--input_schema", required=True)
ap.add_argument("--output_schema", required=True)
ap.add_argument("--app_name", default="")
ap.add_argument("--seed", type=int, default=7)
ap.add_argument("--n_feeders", type=int, default=24)
ap.add_argument("--as_of", default="")
ap.add_argument("--src_dir", default="")
A, _ = ap.parse_known_args(sys.argv[1:])
if A.src_dir:
    sys.path.insert(0, f"{A.src_dir}/src")

from pyspark.sql import SparkSession  # noqa: E402
from pyspark.sql import functions as F  # noqa: E402
from pyspark.sql import types as ST  # noqa: E402

import pandas as pd  # noqa: E402

from armor import contract, demo  # noqa: E402

spark = SparkSession.builder.getOrCreate()
C = contract.load_contract()
SPARK_TYPE = {"string": "string", "date": "date", "timestamp": "timestamp", "double": "double", "long": "bigint",
              "int": "int", "boolean": "boolean"}

as_of = A.as_of or f"{date.today().year}-01-01"
S = demo.DemoSettings(seed=A.seed, n_feeders=A.n_feeders, as_of=as_of)
T = demo.generate(S)
print(f"demo utility: {A.n_feeders} feeders, seed {A.seed}, as of {as_of}")

for schema, what in ((A.input_schema, "ARMOR demo asset data model: a fictional utility generated by armor.demo (synthetic)"),
                     (A.output_schema, "ARMOR outputs: probability model + decision engine")):
    spark.sql(f"CREATE SCHEMA IF NOT EXISTS {schema} COMMENT '{what}'")

for name, df in T.items():
    spec = C["tables"].get(name, {}).get("columns")
    if spec:
        # An explicit schema (strings, doubles, booleans), so all-null columns never depend on inference; then cast
        # to the data model's declared types, in its column order.
        kind = {c: ("double" if spec[c]["type"] in ("double", "long", "int") else "boolean" if spec[c]["type"] == "boolean" else "string")
                for c in spec}
        st = {"double": ST.DoubleType(), "boolean": ST.BooleanType(), "string": ST.StringType()}
        conv = {"double": float, "boolean": bool, "string": str}
        rows = [[None if pd.isna(v) else conv[kind[c]](v) for c, v in zip(spec, r)] for r in df[list(spec)].itertuples(index=False)]
        sdf = spark.createDataFrame(rows, ST.StructType([ST.StructField(c, st[kind[c]]) for c in spec]))
        sdf = sdf.select([F.col(c).cast(SPARK_TYPE[spec[c]["type"]]).alias(c) for c in spec])
    else:
        sdf = spark.createDataFrame(df)
    target = f"{A.input_schema}.{name}"
    sdf.write.mode("overwrite").option("overwriteSchema", "true").saveAsTable(target)
    grain = C["tables"].get(name, {}).get("grain") or "Planted truth: the life law (median, Weibull shape, source) that generated each cohort's end of life."
    spark.sql(f"COMMENT ON TABLE {target} IS 'Demo (synthetic). {grain.replace(chr(39), '')}'")
    print(f"wrote {target}: {len(df):,} rows")

# the app reads both schemas as its service principal
if A.app_name:
    try:
        from databricks.sdk import WorkspaceClient
        sp = WorkspaceClient().apps.get(A.app_name).service_principal_client_id
        catalog = A.input_schema.split(".")[0]
        grants = [f"GRANT USE CATALOG ON CATALOG {catalog} TO `{sp}`"]
        for schema in (A.input_schema, A.output_schema):
            grants += [f"GRANT USE SCHEMA, SELECT ON SCHEMA {schema} TO `{sp}`"]
        for g in grants:
            try:
                spark.sql(g)
                print("granted:", g)
            except Exception as e:   # e.g. no MANAGE on the catalog: say so, the README has the manual grant
                print(f"grant not applied ({type(e).__name__}): {g}")
    except Exception as e:
        print(f"app {A.app_name} not found ({type(e).__name__}); deploy the bundle first, then grant (README)")
print('{"status": "ok"}')
